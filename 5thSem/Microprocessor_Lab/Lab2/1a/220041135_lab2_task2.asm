ORG 0100h
START:

MOV AH, 1
INT 21h 

MOV BL, AL
CMP BL, 96
JG SMALLER
JMP GREATER
                   
SMALLER:
SUB BL, 32
JMP NEXT_STEP                   

GREATER:
ADD BL, 32   

NEXT_STEP:
MOV CL, 05h

COUNT_NEXT_FIVE:
DEC CL
INC BL
MOV AH, 2
MOV DL, BL
INT 21h
CMP CL, 0
JNZ COUNT_NEXT_FIVE

MOV CL, 5
SUB BL, 05h

COUNT_BEFORE_FIVE:
DEC CL
DEC BL
MOV AH, 2
MOV DL, BL
INT 21h
CMP CL, 0
JNZ COUNT_BEFORE_FIVE


END_PROGRAM:
MOV AH, 4CH
INT 21H

END START
